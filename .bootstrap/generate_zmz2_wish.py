def validate(person: Path) -> None:
    errors: list[str] = []
    wish = person / "WISH_LIST.md"
    text = wish.read_text(encoding="utf-8")
    if len(text.splitlines()) <= 1000:
        errors.append(f"WISH_LIST.md must exceed 1000 lines; found {len(text.splitlines())}")
    headings = re.findall(r"^### 第 \d{3} 个愿望：", text, flags=re.M)
    if len(headings) != 120:
        errors.append(f"expected 120 wishes; found {len(headings)}")
    with (person / "attachments/06_IDEA_BACKLOG.csv").open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != 41:
        errors.append(f"expected 41 ideas; found {len(rows)}")
    for svg in (person / "assets").glob("*.svg"):
        try:
            ET.parse(svg)
        except ET.ParseError as exc:
            errors.append(f"invalid SVG {svg.name}: {exc}")
    if len(list((person / "assets").glob("*.svg"))) != 3:
        errors.append("expected 3 SVG files")
    if errors:
        raise RuntimeError("; ".join(errors))


def main(argv: Sequence[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
